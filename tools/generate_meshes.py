#!/usr/bin/env python3
"""Genera mallas Wavefront .obj optimizadas para PS2 GS (fusión colineal de quads
y culling de caras internas) a partir de archivos JSON de mapas de HK Engine 1."""

from __future__ import annotations
import json
import sys
from collections import defaultdict
from pathlib import Path

CELL_SIZE = 2.0
WALL_HEIGHT = 2.6
WALL_TYPES = {
    1: "walls_1.obj",
    2: "walls_2.obj",
    3: "walls_3.obj",
    4: "exit.obj",
    5: "gates.obj",
}


def exposed_runs(grid):
    edges = defaultdict(set)
    h, w = len(grid), len(grid[0])
    for gy, row in enumerate(grid):
        for gx, val in enumerate(row):
            if val not in WALL_TYPES:
                continue
            sides = (
                ("west", gx - 1, gy, gx, gy),
                ("east", gx + 1, gy, gx + 1, gy),
                ("north", gx, gy - 1, gy, gx),
                ("south", gx, gy + 1, gy + 1, gx),
            )
            for direction, nx, ny, plane, seg in sides:
                if 0 <= nx < w and 0 <= ny < h and grid[ny][nx] == 0:
                    edges[(val, direction, plane)].add(seg)

    runs = defaultdict(list)
    for (val, direction, plane), segs in edges.items():
        ordered = sorted(segs)
        if not ordered:
            continue
        start = prev = ordered[0]
        for s in ordered[1:] + [None]:
            if s is not None and s == prev + 1:
                prev = s
                continue
            runs[val].append((direction, plane, start, prev + 1))
            if s is not None:
                start = prev = s
    return runs


def quad_verts(direction, plane, start, end):
    p, a, b, h = plane * CELL_SIZE, start * CELL_SIZE, end * CELL_SIZE, WALL_HEIGHT
    if direction == "west":
        return [(p, 0, a), (p, 0, b), (p, h, b), (p, h, a)], (-1, 0, 0)
    if direction == "east":
        return [(p, 0, b), (p, 0, a), (p, h, a), (p, h, b)], (1, 0, 0)
    if direction == "north":
        return [(b, 0, p), (a, 0, p), (a, h, p), (b, h, p)], (0, 0, -1)
    return [(a, 0, p), (b, 0, p), (b, h, p), (a, h, p)], (0, 0, 1)


def write_wall_obj(path: Path, quads):
    lines = ["# Generated by HK Engine 1 mesh compiler"]
    for d, pl, st, en in quads:
        verts, _ = quad_verts(d, pl, st, en)
        lines.extend("v %.4f %.4f %.4f" % v for v in verts)
    for _, _, st, en in quads:
        ln = en - st
        lines.extend(("vt 0.0000 0.0000", f"vt {ln:.4f} 0.0000", f"vt {ln:.4f} 1.0000", "vt 0.0000 1.0000"))
    for d, pl, st, en in quads:
        _, n = quad_verts(d, pl, st, en)
        lines.append("vn %.1f %.1f %.1f" % n)
    for idx in range(len(quads)):
        b = idx * 4 + 1
        lines.append(f"f {b}/{b}/{idx+1} {b+1}/{b+1}/{idx+1} {b+2}/{b+2}/{idx+1}")
        lines.append(f"f {b}/{b}/{idx+1} {b+2}/{b+2}/{idx+1} {b+3}/{b+3}/{idx+1}")
    path.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    return len(quads) * 2


def write_slab_obj(path: Path, grid, y_level: float, is_ceiling: bool):
    quads = []
    for gy, row in enumerate(grid):
        gx, w = 0, len(row)
        while gx < w:
            if row[gx] != 0:
                gx += 1
                continue
            st = gx
            while gx < w and row[gx] == 0:
                gx += 1
            quads.append((gy, st, gx))
    lines = ["# Generated by HK Engine 1 slab compiler"]
    n = (0, -1, 0) if is_ceiling else (0, 1, 0)
    for gy, x0, x1 in quads:
        ax, bx, az, bz = x0 * CELL_SIZE, x1 * CELL_SIZE, gy * CELL_SIZE, (gy + 1) * CELL_SIZE
        verts = [(ax, y_level, az), (bx, y_level, az), (bx, y_level, bz), (ax, y_level, bz)] if is_ceiling else [(ax, y_level, bz), (bx, y_level, bz), (bx, y_level, az), (ax, y_level, az)]
        lines.extend("v %.4f %.4f %.4f" % v for v in verts)
    for _, x0, x1 in quads:
        ln = x1 - x0
        lines.extend(("vt 0.0000 0.0000", f"vt {ln:.4f} 0.0000", f"vt {ln:.4f} 1.0000", "vt 0.0000 1.0000"))
    lines.append("vn %.1f %.1f %.1f" % n)
    for idx in range(len(quads)):
        b = idx * 4 + 1
        lines.append(f"f {b}/{b}/1 {b+1}/{b+1}/1 {b+2}/{b+2}/1")
        lines.append(f"f {b}/{b}/1 {b+2}/{b+2}/1 {b+3}/{b+3}/1")
    path.write_text("\n".join(lines) + "\n", encoding="ascii", newline="\n")
    return len(quads) * 2


def compile_map_json(map_path: Path, out_models_dir: Path) -> int:
    data = json.loads(map_path.read_text(encoding="utf-8"))
    grid = data["grid"]
    map_id = map_path.stem
    out_models_dir.mkdir(parents=True, exist_ok=True)
    runs = exposed_runs(grid)
    total = 0
    for wtype, suffix in WALL_TYPES.items():
        if runs.get(wtype):
            total += write_wall_obj(out_models_dir / f"{map_id}_{suffix}", runs[wtype])
    total += write_slab_obj(out_models_dir / f"{map_id}_floor.obj", grid, 0.0, False)
    total += write_slab_obj(out_models_dir / f"{map_id}_ceiling.obj", grid, WALL_HEIGHT, True)
    return total


if __name__ == "__main__":
    if len(sys.argv) < 3:
        print("Uso: python3 tools/generate_meshes.py <carpeta_maps> <carpeta_models_salida>")
        raise SystemExit(1)
    maps_dir, out_dir = Path(sys.argv[1]), Path(sys.argv[2])
    for mp in sorted(maps_dir.glob("*.json")):
        tris = compile_map_json(mp, out_dir)
        print(f"[MESH] {mp.stem}: {tris} triangulos totales")
